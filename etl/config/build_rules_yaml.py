"""Build etl/config/dl_rules.yaml from docs/approved_data_rules.md (read only).

The approved document is authoritative. This script copies its machine-readable
catalog verbatim, adds each rule's `description` (the Rule cell of the rule
tables; for a two-part ID, that part's sentence), and adds the dataset registry,
factors, labels and DQ parameters the builder needs. Re-run it whenever the
approved document changes:

    python etl/config/build_rules_yaml.py
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[2]
DOC = ROOT / "docs" / "approved_data_rules.md"
OUT = Path(__file__).resolve().parent / "dl_rules.yaml"

REGISTRY = {
    "version": 1,
    "approved_doc": "docs/approved_data_rules.md",
    "dataset_order": ["transactions", "industry", "sm_spend"],
    "datasets": {
        "transactions": {
            "label": "Transactions",
            "staging_prefix": "transactions/",
            "columns": ["ID", "month", "amount"],
            "key_columns": ["ID", "month"],
            "money_factor": 10000,
        },
        "industry": {
            "label": "Industry",
            "staging_prefix": "industry/",
            "columns": ["ID", "Industria"],
            "key_columns": ["ID"],
        },
        "sm_spend": {
            "label": "S&M spend",
            "staging_prefix": "s_and_m/",
            "columns": ["Month", "PaidMedia", "Travel", "PublicidadNoWeb", "Freelance",
                        "SoftwareTools", "Team", "PayrollExpenses"],
            "key_columns": ["Month"],
            "money_factor": 100000000,
        },
    },
    "dq": {
        "status_pass_pct": 100,
        "status_warn_min_pct": 99,
        "trend_runs": 24,
        "serving_page_size": 200,
        "api_max_page_size": 200,
    },
}


def _rule_cells(md: str) -> dict[str, str]:
    cells: dict[str, str] = {}
    for line in md.splitlines():
        m = re.match(r"^\| ((?:BRZ|CTO|CDO|SQ|SB|CFO|CRO)-\d+) \|", line)
        if not m:
            continue
        parts = [p.strip() for p in line.strip().strip("|").split(" | ")]
        if len(parts) != 11:  # the deferred table has 4 columns; skip it
            continue
        cells[m.group(1)] = parts[3]
    return cells


def _split_two_part(text: str) -> tuple[str, str]:
    i_a, i_b = text.find("(a) "), text.find(" (b) ")
    pre = text[:i_a].strip()
    a = text[i_a + 4:i_b].strip()
    b = text[i_b + 5:].strip()
    return (f"{pre} {a}".strip(), f"{pre} {b}".strip())


def build() -> dict:
    md = DOC.read_text(encoding="utf-8")
    block = re.search(r"## Machine-readable catalog\s+```yaml\n(.*?)```", md, re.S)
    if not block:
        sys.exit("catalog block not found")
    catalog = yaml.safe_load(block.group(1))["rule_catalog"]
    cells = _rule_cells(md)
    for rule in catalog:
        rid = rule["id"]
        base = rid[:-1] if rid[-1] in "ab" and rid[:-1] in cells else rid
        text = cells[base]
        if base != rid:
            a, b = _split_two_part(text)
            text = a if rid.endswith("a") else b
        rule["description"] = text
    return {**REGISTRY, "rule_catalog": catalog}


def main() -> None:
    cfg = build()
    header = ("# GENERATED by etl/config/build_rules_yaml.py from docs/approved_data_rules.md.\n"
              "# Do not edit by hand: change the approved document and re-run the script.\n")
    text = header + yaml.safe_dump(cfg, sort_keys=False, allow_unicode=True, width=10_000)
    OUT.write_text(text, encoding="utf-8")
    # The Lambda runtime has no PyYAML, so the same config ships as JSON too.
    import hashlib
    import json
    cfg["rules_version"] = "sha256:" + hashlib.sha256(text.encode("utf-8")).hexdigest()[:16]
    OUT.with_suffix(".json").write_text(json.dumps(cfg, ensure_ascii=False, indent=1), encoding="utf-8")
    print(f"wrote {OUT} with {len(cfg['rule_catalog'])} catalog entries")


if __name__ == "__main__":
    main()
